#!/usr/bin/env python3
"""Generate a SQL boundary type contract from STEP-04 catalog metadata only.

Input is the JSON object captured by the isolated database test runner, with
``columns`` (information_schema.columns) and ``enums`` (pg_enum) arrays. No row
data, database URL, environment secrets, network connection, or SDK is needed.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "src/data/database.types.ts"
SCHEMAS = ("public", "internal")
# The initial metadata snapshot has columns but no relation-kind field. This
# explicit view is defined in the same migration. Future views must be added to
# the metadata's optional ``views`` array rather than guessed from their names.
FOUNDATION_VIEWS = {("public", "qualification_catalog")}


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def generate(metadata: dict[str, Any]) -> str:
    """Fail closed for unsupported types instead of emitting any/unknown."""
    enums = {
        (enum["schema"], enum["name"]): tuple(enum["values"])
        for enum in metadata["enums"]
    }
    relations: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for column in metadata["columns"]:
        key = (column["table_schema"], column["table_name"])
        if key[0] not in SCHEMAS:
            raise ValueError(f"Unexpected schema in metadata: {key[0]}")
        if any(c["column_name"] == column["column_name"] for c in relations[key]):
            raise ValueError(f"Duplicate metadata column: {key}.{column['column_name']}")
        relations[key].append(column)

    views = FOUNDATION_VIEWS | {
        (view["table_schema"], view["table_name"])
        for view in metadata.get("views", [])
    }
    missing_views = views - relations.keys()
    if missing_views:
        raise ValueError(f"Missing view columns in metadata: {sorted(missing_views)}")

    def column_type(column: dict[str, Any]) -> str:
        enum_key = (column["udt_schema"], column["udt_name"])
        if enum_key in enums:
            base = f"DatabaseEnums[{quoted('.'.join(enum_key))}]"
        else:
            scalar_types = {
                "text": "string",
                "uuid": "string",
                "int2": "number",
                "int4": "number",
                "int8": "BigintText",
                "numeric": "DecimalText",
                "bool": "boolean",
                "date": "DateText",
                "timestamptz": "TimestampText",
                "json": "Json",
                "jsonb": "Json",
            }
            if column["udt_schema"] != "pg_catalog" or column["udt_name"] not in scalar_types:
                raise ValueError(f"Unsupported SQL type: {enum_key}")
            base = scalar_types[column["udt_name"]]
        return base + (" | null" if column["is_nullable"] == "YES" else "")

    migrations = sorted((PROJECT_ROOT / "supabase/migrations").glob("*.sql"))
    if not migrations:
        raise ValueError("No schema migrations found")
    lines = [
        "// Generated by scripts/generate-db-types.py from actual PostgreSQL catalog metadata.",
        "// Migration source: " + ", ".join(path.name for path in migrations),
        "// Do not edit. Re-run the generator after applying migrations to an isolated DB.",
        "// This is a SQL repository boundary contract, not Supabase CLI/PostgREST output.",
        "// Configure the future SQL decoder to preserve bigint/numeric as strings and",
        "// date/timestamptz as ISO text. In particular, default node-pg timestamps are Date.",
        "// Do not cast PostgREST JSON numbers to these strings after precision was lost.",
        "// Text CHECK constraints, URL validation, and privileges still require DB/runtime checks.",
        "",
        "export type BigintText = string;",
        "export type DecimalText = string;",
        "export type DateText = string;",
        "export type TimestampText = string;",
        "export type Json = string | number | boolean | null | Json[] | { [key: string]: Json };",
        "",
        "export type DatabaseEnums = {",
    ]
    for key, values in sorted(enums.items()):
        lines.append(f"  {quoted('.'.join(key))}: " + " | ".join(map(quoted, values)) + ";")
    lines.extend([
        "};",
        "",
        "type Table<Row, Optional extends keyof Row = never, Generated extends keyof Row = never> = {",
        "  Row: Row;",
        "  Insert: Omit<Row, Optional | Generated> & Partial<Pick<Row, Optional>> & { [K in Generated]?: never };",
        "  Update: Partial<Omit<Row, Generated>> & { [K in Generated]?: never };",
        "};",
        "",
        "export type Database = {",
    ])

    for schema in SCHEMAS:
        lines.extend([f"  {schema}: {{", "    Tables: {"])
        schema_relations = sorted(k for k in relations if k[0] == schema)
        for key in schema_relations:
            if key in views:
                continue
            columns = relations[key]
            lines.append(f"      {key[1]}: Table<{{")
            for column in columns:
                lines.append(f"        {column['column_name']}: {column_type(column)};")
            generated = [c["column_name"] for c in columns if c["is_generated"] != "NEVER"]
            optional = [
                c["column_name"] for c in columns
                if c["is_generated"] == "NEVER" and
                (c["is_nullable"] == "YES" or c["column_default"] is not None)
            ]
            keys = lambda values: " | ".join(map(quoted, values)) or "never"
            lines.append(f"      }}, {keys(optional)}, {keys(generated)}>;")
        lines.extend(["    };", "    Views: {"])
        for key in schema_relations:
            if key not in views:
                continue
            lines.append(f"      {key[1]}: {{")
            lines.append("        Row: {")
            for column in relations[key]:
                lines.append(f"          {column['column_name']}: {column_type(column)};")
            lines.extend(["        };", "        Insert: never;", "        Update: never;", "      };"])
        if not any(key in views for key in schema_relations):
            # A mapped empty property set avoids the misleading broad TS `{}` type.
            lines[-1] = "    Views: Record<string, never>;"
        else:
            lines.append("    };")
        schema_enums = [(key, values) for key, values in sorted(enums.items()) if key[0] == schema]
        if schema_enums:
            lines.append("    Enums: {")
            for key, _ in schema_enums:
                lines.append(f"      {key[1]}: DatabaseEnums[{quoted('.'.join(key))}];")
            lines.append("    };")
        else:
            lines.append("    Enums: Record<string, never>;")
        lines.append("  };")
    lines.extend([
        "};",
        "",
        "export type PublicDatabase = Database[\"public\"];",
        "// Internal types are server-only design contracts; they confer no SQL grants.",
        "export type InternalDatabase = Database[\"internal\"];",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("metadata", type=Path, help="Row-free catalog metadata JSON")
    parser.add_argument("--check", action="store_true", help="Fail if generated output differs")
    args = parser.parse_args()
    generated = generate(json.loads(args.metadata.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            print("Database type contract is missing or differs from catalog metadata.")
            return 1
        print("Database type contract matches catalog metadata.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(PROJECT_ROOT)} from row-free catalog metadata.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
